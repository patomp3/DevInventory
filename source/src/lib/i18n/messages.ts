export const MESSAGES: Record<Locale, Record<MsgKey, string>> = { th, en };

/** แปลข้อความ + แทนที่ {param} (ไม่พบ key = ใช้ไทย แล้วค่อยคืน key เพื่อให้เห็นว่าลืมเพิ่ม) */
export function translate(locale: Locale, key: MsgKey, params?: Record<string, string | number>): string {
  let s = MESSAGES[locale]?.[key] ?? MESSAGES.th[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
